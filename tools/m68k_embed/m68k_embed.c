// Embeds a vasm hunk object into the POSIX build (TORNADO_68K_EMU).
//
//   m68k_embed <input.o> <output.c> <module name>
//
// The generated C file holds the object as a byte array and registers it with
// tndo_m68k_register_module() from a constructor, so the module is loaded by
// tndo_m68k_init() without any file access at runtime.

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv) {
  if (argc != 4) {
    fprintf(stderr, "usage: %s <input.o> <output.c> <module name>\n",
            argv[0]);
    return 2;
  }
  FILE *in = fopen(argv[1], "rb");
  if (!in) {
    perror(argv[1]);
    return 1;
  }
  FILE *out = fopen(argv[2], "w");
  if (!out) {
    perror(argv[2]);
    fclose(in);
    return 1;
  }

  // The module name ends up in a C string literal.
  for (const char *p = argv[3]; *p; p++) {
    if (*p == '"' || *p == '\\' || *p < 32) {
      fprintf(stderr, "%s: invalid character in module name\n", argv[0]);
      return 1;
    }
  }

  fprintf(out, "// Generated by m68k_embed from %s. Do not edit.\n\n",
          argv[1]);
  fprintf(out, "#include \"tndo_m68k.h\"\n\n");
  fprintf(out, "static const unsigned char module_data[] = {");
  unsigned long n = 0;
  int c;
  while ((c = fgetc(in)) != EOF) {
    fprintf(out, "%s0x%02x,", (n % 16) ? " " : "\n    ", c);
    n++;
  }
  fprintf(out, "\n};\n\n");
  fprintf(out, "__attribute__((constructor)) static void register_module(void) "
               "{\n");
  fprintf(out,
          "  tndo_m68k_register_module(\"%s\", module_data, "
          "sizeof(module_data));\n",
          argv[3]);
  fprintf(out, "}\n");

  int err = ferror(in) || ferror(out);
  fclose(in);
  if (fclose(out) || err || n == 0) {
    fprintf(stderr, "%s: failed to embed %s\n", argv[0], argv[1]);
    remove(argv[2]);
    return 1;
  }
  return 0;
}
